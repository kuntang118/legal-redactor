def main() -> int:
    preset = load_preset(Path(__file__).resolve().parents[1] / "schemas" / "legal.yaml")
    pipe = TextPipeline(preset)
    spans = pipe.detect_text(TEXT, "body")

    print(f"检出 {len(spans)} 个 span\n")
    by_type: dict[str, list] = {}
    for s in spans:
        by_type.setdefault(s.etype, []).append(s)
    for t in sorted(by_type, key=lambda k: -len(by_type[k])):
        items = by_type[t]
        print(f"== {t} ({len(items)}) ==")
        for s in items[:12]:
            flag = ""
            if s.attrs.get("escalated"):
                flag = " [升级]"
            if s.action == "review":
                flag += " [待复核]"
            print(f"   [{s.start:5d}-{s.end:5d}] conf={s.confidence:.2f}{flag} "
                  f"{s.text!r}  <- {s.reason}")
        if len(items) > 12:
            print(f"   …另有 {len(items)-12} 条")
        print()
    return 0


