def contains_generic_word(name: str, only_at_start: bool = False) -> str | None:
    """候选姓名里若含通用词，返回该词；否则 None。

    only_at_start=True 时只看从姓氏位置开始的 2 字词——
    这是"支付定金""高级法院"这类误报的主要形态；
    而"王文明"里的"文明"起于第 2 字，更可能是真名，角色词路径下放过。
    """
    rng = range(1) if only_at_start else range(len(name) - 1)
    for i in rng:
        w = name[i:i + 2]
        if w in GENERIC_WORDS:
            return w
    if name in GENERIC_WORDS:
        return name
    return None


# 重建非人名词表（把追加的高风险词并入）
